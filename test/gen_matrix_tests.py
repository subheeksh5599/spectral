def cell(name, setup, body, doc):
    call = setup if setup.startswith("_") else "_" + setup
    return (
        f"    /// @dev {doc}\n"
        f"    function test_{name}() public {{\n"
        f"        uint256 id = {call}();\n"
        f"{body}"
        f"    }}\n"
    )


def expect_revert(err, extra=""):
    return f"        vm.expectRevert({err}{extra});\n"



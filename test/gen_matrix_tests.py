#!/usr/bin/env python3
"""Generates test/SpectralMatrix.t.sol — the venue's conformance matrix.

Every cell is a distinct guard test: a state, an operation, an actor, and the exact
outcome the contract must produce (a named error selector, or a specific resulting
state). The matrix is exhaustive over states × operations × actors, so a missing or
weakened guard anywhere shows up as a failing cell rather than as a silent gap.

Reach a given state through the public API only — no storage pokes, so the setups
themselves are part of what is being tested.

Run:  python3 test/gen_matrix_tests.py   (then: forge test)
"""

